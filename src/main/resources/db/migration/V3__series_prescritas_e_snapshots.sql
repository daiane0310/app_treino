-- Additive only. Existing prescriptions and execution snapshots remain LEGADO.
-- No historical results or legacy values are rewritten.
ALTER TABLE treino_exercicios ADD COLUMN formato_prescricao VARCHAR(20) NOT NULL DEFAULT 'LEGADO'
    CHECK (formato_prescricao IN ('LEGADO', 'POR_SERIE'));
ALTER TABLE execucoes_exercicio ADD COLUMN formato_prescricao VARCHAR(20) NOT NULL DEFAULT 'LEGADO'
    CHECK (formato_prescricao IN ('LEGADO', 'POR_SERIE'));

CREATE TABLE series_prescritas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treino_exercicio_id BIGINT NOT NULL REFERENCES treino_exercicios(id),
    numero_serie INTEGER NOT NULL CHECK (numero_serie > 0),
    repeticoes INTEGER CHECK (repeticoes >= 0),
    carga NUMERIC(10,2) CHECK (carga >= 0),
    CONSTRAINT uk_serie_prescrita_numero UNIQUE (treino_exercicio_id, numero_serie)
);

CREATE TABLE execucoes_series_prescritas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execucao_exercicio_id BIGINT NOT NULL REFERENCES execucoes_exercicio(id),
    numero_serie INTEGER NOT NULL CHECK (numero_serie > 0),
    repeticoes_planejadas INTEGER CHECK (repeticoes_planejadas >= 0),
    carga_planejada NUMERIC(10,2) CHECK (carga_planejada >= 0),
    CONSTRAINT uk_snapshot_serie_numero UNIQUE (execucao_exercicio_id, numero_serie)
);
